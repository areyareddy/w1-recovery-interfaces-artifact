"""A fixed-policy, verifier-in-the-loop agent harness for the W1/W2 experiments.

WHAT THIS IS, AND WHAT IT IS NOT.

This module is a *formalization*, not a new experiment. Every branch analysed in either
paper was generated by the frozen runner (`src/runner.py`, driven by `scripts/s12_run.py`)
under the frozen spec. This file does not generate anything, does not call a server, and
does not touch the frozen runner. It expresses the policies that were executed as an
explicit state machine, and `scripts/s34_agent_loop_replay.py` replays the recorded data
through it to prove that the state machine reproduces the executed decisions exactly.

**It is a fixed-policy verifier-in-the-loop agent. It is not an adaptive or learned
controller, and no adaptive controller was evaluated.** Be precise about where the
verifier closes the loop:

  - ACTION SELECTION is fixed. The policy's action sequence is determined before the
    trajectory starts and never depends on a verifier result.
  - ACTION CONTENT depends on history: REPAIR conditions its prompt on the previous
    attempt. REGENERATE ignores it.
  - TERMINATION depends on the verifier. STOP fires on a verified proof, on an exhausted
    budget, or when the policy's plan runs out.

That single feedback edge -- verify -> stop -- is the whole of the closed loop. Claiming
more would misdescribe what ran. The router that would have made action selection adaptive
is withdrawn (spec/ALLOCATION_SPEC.md section 6) and is not implemented here.

THE STARTING STATE IS NOT EMPTY. The 83-root set is *defined* by each root having a prior
failed proof attempt, so every trajectory begins at attempt_index 1 with previous_attempt
already populated and verifier_result already 'failed'. This is what makes W1's contrast
exact: arm A and arm C are two alternative ACTIONS taken from an identical state --
REGENERATE, which discards the prior attempt, versus REPAIR, which conditions on it. They
are not steps 1 and 2 of one trajectory.

    W1  A  =  REGENERATE from the seeded state      (fresh prompt, prior attempt unseen)
        C  =  REPAIR     from the same state        (prior attempt in context)

    W2  Long     =  REGENERATE(12288) -> STOP
        Split-2  =  up to 2 x REGENERATE(6144), stopping on verification
        Split-3  =  up to 3 x REGENERATE(4096), stopping on verification

All three W2 policies spend the same 12,288-token budget; they differ only in how it is
divided. Per spec/ALLOCATION_SPEC.md section 4 every draw was generated unconditionally,
and the stop-after-first-success policy is computed by truncating each root's executed
draw sequence at its first verified draw. That rule was fixed before any outcome was seen;
`accounting()` below implements it and nothing else.
"""

from __future__ import annotations

import sqlite3
from dataclasses import dataclass, field, replace
from enum import Enum
from pathlib import Path


class Action(Enum):
    """The three actions. REPAIR is the only one that reads the previous attempt."""
    REGENERATE = "REGENERATE"   # fresh A-style prompt; prior attempt discarded
    REPAIR = "REPAIR"           # C-style prompt; prior attempt in context
    STOP = "STOP"


class StopReason(Enum):
    VERIFIED = "verified"                    # a draw produced a Lean-accepted proof
    BUDGET_EXHAUSTED = "budget_exhausted"    # no affordable action remains
    POLICY_EXHAUSTED = "policy_exhausted"    # the fixed plan ran out


@dataclass(frozen=True)
class State:
    """Everything the policy and the transition may read."""
    theorem: str
    previous_attempt: str | None = None      # populated at entry: see module docstring
    verifier_result: str | None = None       # outcome_state of the most recent draw
    remaining_budget: int = 0                # completion tokens still committable
    elapsed_tokens: int = 0                  # completion tokens actually consumed
    elapsed_seconds: float = 0.0             # serving + verifier wall time
    attempt_index: int = 0                   # draws taken so far
    verified: bool = False


@dataclass(frozen=True)
class Step:
    """One generate -> extract -> verify -> record transition."""
    attempt_index: int
    action: Action
    cap: int
    branch_key: str
    outcome_state: str
    verified: bool
    completion_tokens: int
    serving_seconds: float
    verifier_seconds: float

    @property
    def total_seconds(self) -> float:
        return self.serving_seconds + self.verifier_seconds


@dataclass
class Trace:
    theorem: str
    policy: str
    budget: int
    steps: list[Step] = field(default_factory=list)
    stop_reason: StopReason | None = None

    def accounting(self, stop_after_first_success: bool) -> dict:
        """The two pre-specified cost accountings (ALLOCATION_SPEC section 4).

        full budget            -- every executed draw is paid for
        stop after first success -- truncate at the first verified draw and pay only for
                                    the draws up to and including it
        """
        steps = self.steps
        if stop_after_first_success:
            cut = next((i for i, s in enumerate(steps) if s.verified), None)
            if cut is not None:
                steps = steps[:cut + 1]
        return {
            "draws": len(steps),
            "verified": any(s.verified for s in steps),
            "completion_tokens": sum(s.completion_tokens for s in steps),
            "seconds": round(sum(s.total_seconds for s in steps), 3),
        }


# --------------------------------------------------------------------------- policies


@dataclass(frozen=True)
class FixedPolicy:
    """A plan fixed before the trajectory starts.

    `plan` is the full action sequence. next_action never inspects verifier_result --
    only the loop's stop rule does. This is what makes the policy non-adaptive, and the
    assertion in next_action keeps it that way if anyone edits this later.
    """
    name: str
    plan: tuple[tuple[Action, int], ...]

    def next_action(self, state: State) -> tuple[Action, int] | None:
        if state.attempt_index >= len(self.plan):
            return None
        action, cap = self.plan[state.attempt_index]
        assert cap <= state.remaining_budget or state.attempt_index == 0, (
            f"{self.name}: draw {state.attempt_index + 1} costs {cap} with "
            f"{state.remaining_budget} left; a fixed plan must fit its own budget")
        return action, cap


BUDGET = 12288  # completion tokens per root, identical for every W2 policy

LONG = FixedPolicy("long", ((Action.REGENERATE, 12288),))
SPLIT2 = FixedPolicy("split2", ((Action.REGENERATE, 6144),) * 2)
SPLIT3 = FixedPolicy("split3", ((Action.REGENERATE, 4096),) * 3)

# W1: one action from the seeded state. Two policies differing only in that action.
REGENERATE_ONCE = FixedPolicy("regenerate_once", ((Action.REGENERATE, 12288),))
REPAIR_ONCE = FixedPolicy("repair_once", ((Action.REPAIR, 12288),))

POLICIES = {p.name: p for p in
            (LONG, SPLIT2, SPLIT3, REGENERATE_ONCE, REPAIR_ONCE)}


# --------------------------------------------------------------------------- backend


class ReplayBackend:
    """Returns the branch that was actually generated. The only backend that exists.

    There is deliberately no live backend here. The experiments were run by the frozen
    runner; giving this module a way to generate would invite the reading that it ran
    them, which it did not.
    """

    def __init__(self, db: Path, key_fn):
        self.con = sqlite3.connect(f"file:{db}?mode=ro", uri=True)
        self.con.row_factory = sqlite3.Row
        self.key_fn = key_fn
        # data/runs.sqlite is the ORIGINAL frozen job store and predates the per-branch
        # max_tokens column that scripts/s29_migrate_timings.py added to the later
        # databases. Where the column is absent the cap cannot be cross-checked against
        # the record, so the check is skipped rather than faked -- and never silently:
        # has_cap is reported by the replay test.
        cols = {r[1] for r in self.con.execute("PRAGMA table_info(branches)")}
        self.has_cap = "max_tokens" in cols

    def draw(self, theorem: str, attempt_index: int, action: Action, cap: int) -> Step:
        key = self.key_fn(theorem, attempt_index, action)
        fields = ("branch_key, outcome_state, verified, completion_tokens, "
                  "request_wall_seconds, verifier_wall_seconds"
                  + (", max_tokens" if self.has_cap else ""))
        row = self.con.execute(
            f"SELECT {fields} FROM branches WHERE branch_key=? AND status='done'",
            (key,)).fetchone()
        if row is None:
            raise LookupError(f"no completed branch {key!r}")
        if self.has_cap and row["max_tokens"] != cap:
            raise ValueError(
                f"{key}: recorded cap {row['max_tokens']} != policy cap {cap}; the "
                "state machine does not describe what ran")
        return Step(
            attempt_index=attempt_index + 1, action=action, cap=cap,
            branch_key=row["branch_key"], outcome_state=row["outcome_state"],
            verified=bool(row["verified"]),
            completion_tokens=row["completion_tokens"] or 0,
            serving_seconds=row["request_wall_seconds"] or 0.0,
            verifier_seconds=row["verifier_wall_seconds"] or 0.0)

    def completion(self, branch_key: str) -> str:
        row = self.con.execute(
            "SELECT completion FROM branches WHERE branch_key=?", (branch_key,)).fetchone()
        return (row["completion"] if row else "") or ""

    def close(self) -> None:
        self.con.close()


# ------------------------------------------------------------------------------ loop


def run(theorem: str, policy: FixedPolicy, backend: ReplayBackend,
        prior_attempt: str | None, budget: int = BUDGET) -> Trace:
    """generate -> extract Lean -> verify -> record resources -> update state.

    Extraction and verification happened inside the frozen runner and are recorded in
    `outcome_state` / `verified`; the replay consumes those rather than redoing them,
    which is what makes this a faithful replay instead of a reinterpretation.
    """
    state = State(theorem=theorem, previous_attempt=prior_attempt,
                  verifier_result="failed" if prior_attempt is not None else None,
                  remaining_budget=budget)
    trace = Trace(theorem=theorem, policy=policy.name, budget=budget)

    while True:
        nxt = policy.next_action(state)
        if nxt is None:
            trace.stop_reason = StopReason.POLICY_EXHAUSTED
            break
        action, cap = nxt
        if cap > state.remaining_budget:
            trace.stop_reason = StopReason.BUDGET_EXHAUSTED
            break

        step = backend.draw(theorem, state.attempt_index, action, cap)
        trace.steps.append(step)

        state = replace(
            state,
            previous_attempt=backend.completion(step.branch_key),
            verifier_result=step.outcome_state,
            remaining_budget=state.remaining_budget - cap,
            elapsed_tokens=state.elapsed_tokens + step.completion_tokens,
            elapsed_seconds=state.elapsed_seconds + step.total_seconds,
            attempt_index=state.attempt_index + 1,
            verified=state.verified or step.verified)

        if state.verified:
            trace.stop_reason = StopReason.VERIFIED
            break

    return trace
