"""Progress dashboard.  Run at any time:  python scripts/status.py

Always rewrites TODO.md as a side effect, so the checked-in status table cannot drift
from what the receipts actually say. --watch N refreshes every N seconds, which is what
to leave running beside a long generation job.

Reads audit/receipts/*.json and the files on disk. Reports nothing it has not verified:
a step counts as done only when its receipt exists AND every input it consumed still
hashes to what it hashed then AND every output it declared is still present and
unchanged. A step whose upstream input moved shows as STALE, not done.

  python scripts/status.py            table + percent complete + the next command
  python scripts/status.py -v         also list each step's declared outputs
  python scripts/status.py --watch 600  refresh TODO.md every 10 minutes
"""

from __future__ import annotations

import json
import sqlite3
import sys
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(HERE))

import pipeline  # noqa: E402
import receipts  # noqa: E402

MARK = {"done": "[x]", "stale": "[!]", "pending": "[ ]", "no-script": "[ ]"}


def branch_progress() -> tuple[int, int] | None:
    """Live branch counter for the generation step, read straight from the job store."""
    db = ROOT / "data/runs.sqlite"
    if not db.exists():
        return None
    try:
        con = sqlite3.connect(f"file:{db}?mode=ro", uri=True)
        # s12 is the 181-branch primary run, not the whole 376-branch store
        done = con.execute("select count(*) from branches where cohort='primary_eval' "
                           "and status='done'").fetchone()[0]
        total = con.execute("select count(*) from branches "
                            "where cohort='primary_eval'").fetchone()[0]
        con.close()
        return done, total
    except sqlite3.Error:
        return None



OPEN_DECISIONS = {
    "seed_block_2_derivation":
        "how eval_seed_block_2 derives from block 1 -- must be declared, not clever",
    "plain_draw_descriptive_variance_band":
        "whether the historic R0 rescue band is pre-registered as arm A's reference",
}


def write_todo(rows, n_done: int, total: int) -> Path:
    """Regenerate TODO.md from the receipts. Never hand-edit that file."""
    pct = 100 * n_done / total
    box = {"done": "x", "stale": "!", "pending": " ", "no-script": " "}
    lines = [
        "# TODO -- W1/W2 harness",
        "",
        f"**{n_done}/{total} steps complete ({pct:.0f}%)**",
        "",
        f"Generated by `python scripts/status.py` at "
        f"{time.strftime('%Y-%m-%d %H:%M:%SZ', time.gmtime())}. Do not hand-edit --",
        "every row is derived from `audit/receipts/*.json` and the files on disk.",
        "",
        "| | Step | Gate | Status | Title | Detail |",
        "|---|---|---|---|---|---|",
    ]
    for step, status, detail in rows:
        note = detail
        if step["id"] == "s12":
            prog = branch_progress()
            if prog and prog[1]:
                note = f"{prog[0]}/{prog[1]} branches ({100 * prog[0] / prog[1]:.0f}%)"
        lines.append(f"| [{box[status]}] | `{step['id']}` | {step['gate']} | {status} "
                     f"| {step['title']} | {note or step['blurb']} |")

    nxt = next((s for s, st, _ in rows if st != "done"), None)
    lines += ["", "## Next", ""]
    if nxt is None:
        lines.append("All steps complete.")
    elif not (ROOT / nxt["script"]).exists():
        lines.append(f"`{nxt['id']}` -- {nxt['title']}. Script not written yet "
                     f"(`{nxt['script']}`).")
    else:
        cmd = nxt["script"].replace("/", chr(92))
        lines += ["```powershell", f"python {cmd}", "```"]

    freeze = ROOT / "audit/step1_freeze.json"
    pending = []
    if freeze.exists():
        pending = json.loads(freeze.read_text(encoding="utf-8")).get(
            "open_decisions_not_frozen", [])
    # once s11 has frozen them these are decisions of record, not open questions --
    # leaving them under an "open" heading would be a false claim in a generated doc
    frozen_rec = receipts.load("s11")
    resolved = (frozen_rec or {}).get("stats", {}).get("open_decisions_resolved", [])
    if pending and not resolved:
        lines += ["", "## Open decisions -- must be settled before `s11` freezes the spec",
                  ""]
        for d in pending:
            lines.append(f"- **{d}** -- {OPEN_DECISIONS.get(d, '')}")
    elif resolved:
        sha = frozen_rec["stats"].get("spec_sha256", "")
        lines += ["", "## Decisions of record", "",
                  f"Frozen in `spec/frozen_spec.yaml` (`{sha[:16]}`):", ""]
        for d in resolved:
            lines.append(f"- **{d}** -- {OPEN_DECISIONS.get(d, '')}")

    lines += ["", "## Verify any of this yourself", "",
              "```powershell",
              "python scripts" + chr(92) + "status.py -v      # per-step declared outputs",
              "python scripts" + chr(92) + "sync_policy.py    # frozen symbols vs CoLM upstream",
              "```",
              ""]
    path = ROOT / "TODO.md"
    path.write_text(chr(10).join(lines), encoding="utf-8", newline=chr(10))
    return path


def bar(frac: float, width: int = 24) -> str:
    filled = int(round(frac * width))
    return "#" * filled + "-" * (width - filled)


def main(argv: list[str]) -> int:
    receipts.force_utf8()
    verbose = "-v" in argv

    if "--watch" in argv:
        i = argv.index("--watch")
        every = int(argv[i + 1]) if len(argv) > i + 1 else 600
        print(f"  watching -- refreshing TODO.md every {every}s. Ctrl+C to stop.")
        while True:
            n = render(verbose)
            print(f"  next refresh in {every}s")
            try:
                time.sleep(every)
            except KeyboardInterrupt:
                print(chr(10) + "  stopped.")
                return 0
            if n is None:
                return 0

    render(verbose)
    return 0


def render(verbose: bool) -> int | None:

    rows = []
    for step in pipeline.STEPS:
        status, detail = receipts.verify(step["id"])
        if status == "pending" and not (ROOT / step["script"]).exists():
            status, detail = "no-script", "not written yet"
        rows.append((step, status, detail))

    n_done = sum(1 for _, s, _ in rows if s == "done")
    total = len(rows)

    print()
    print(f"  W1/W2 harness -- {n_done}/{total} steps complete "
          f"({100 * n_done / total:.0f}%)")
    print(f"  [{bar(n_done / total)}]")
    print()
    print(f"  {'':4}{'step':4} {'gate':5} {'status':9} title")
    print(f"  {'-' * 74}")

    for step, status, detail in rows:
        note = detail
        if step["id"] == "s12":
            prog = branch_progress()
            if prog and prog[1]:
                note = f"{prog[0]}/{prog[1]} branches ({100 * prog[0] / prog[1]:.0f}%)"
        print(f"  {MARK[status]:4}{step['id']:4} {step['gate']:5} {status:9} "
              f"{step['title']}")
        if note:
            print(f"  {'':19} {note}")
        if verbose:
            print(f"  {'':19} {step['blurb']}")
            for out in step["outputs"]:
                have = "ok " if (ROOT / out).exists() else "-- "
                print(f"  {'':19}   {have}{out}")

    todo = write_todo(rows, n_done, total)
    nxt = next((s for s, st, _ in rows if st != "done"), None)
    print()
    print(f"  wrote {todo.relative_to(ROOT).as_posix()}")
    if nxt is None:
        print("  all steps complete.")
    elif not (ROOT / nxt["script"]).exists():
        print(f"  NEXT: {nxt['id']} {nxt['title']} -- script not written yet "
              f"({nxt['script']})")
    else:
        print(f"  NEXT: python {nxt['script']}")
    print()
    return n_done


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
